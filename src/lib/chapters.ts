export interface Question {
  id: string;
  type: "choice" | "dragdrop";
  questionText: string;
  audioText?: string; // ข้อความสำหรับใช้กับ Web Speech API อ่านให้เด็กฟัง
  // สำหรับ Choice
  options?: string[];
  correctAnswer?: string;
  // สำหรับ Drag & Drop
  dragItems?: string[]; // คำตอบที่ให้ลาก
  dropSlots?: { label: string; answer: string }[]; // ช่องที่ให้เอาคำตอบไปวาง
  // การแสดงผลรูปภาพด้วย Emoji (เหมาะกับเด็ก ป.1 ที่ต้องนับจำนวน)
  imageEmoji?: string; // เช่น "🍎", "🐶", "🚗"
  imageCount?: number; // จำนวนภาพที่จะแสดงให้นับ เช่น 5 เพื่อให้เด็กนับแอปเปิ้ล 5 ผล
  
  // สำหรับการจัดแสดงผลแบ่งฝั่ง ซ้าย-ขวา (เช่น โจทย์เปรียบเทียบ หรือ การบวก/ลบ 2 ฝั่ง)
  leftEmoji?: string;
  leftCount?: number;
  rightEmoji?: string;
  rightCount?: number;
}

